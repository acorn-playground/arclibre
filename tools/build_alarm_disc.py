"""Build the distributable !Alarm floppy (arclibre-alarm.adf).

RISC OS 3.11 had Alarm in ROM; ArcLibre ships it on disc, by owner decision,
to make room for the networking modules. The application directory follows
the original Makefile's `install` target (the disc version): !Boot, !Help,
!Run, !RunImage, Alarms, Code, Messages and Templates. As in the ROM build,
the templates are the flat (2D) ones of the Archimedes desktop, !RunImage is
the pinned program compacted by the ArcLibre squish tool, and Code is the
output of the original AlarmSrc (tools/generate_alarm_code.py).
"""
import datetime,hashlib,json,sys
from paths import REPO,SRC
import basic_squish
sys.path.insert(0,str(REPO/'tests'));import check_basic_squish
from adfs_fixture import u24,directory,entry,oldcheck
ROOT=REPO/'build/alarm-disc';ROOT.mkdir(parents=True,exist_ok=True)
def sha(b):return hashlib.sha256(b).hexdigest()
pins={r['path']:r for r in json.loads((REPO/'manifests/desktop-utility-inputs.json').read_text()) if r['component']=='Alarm'}
def pinned(path):
 b=(SRC/'Alarm'/path).read_bytes();assert sha(b)==pins[path]['sha256'],path;return b
program=pinned('bas/!RunImage,ffb')
runimage,names=basic_squish.squish(program)
evidence=check_basic_squish.check('Alarm/bas/!RunImage,ffb',program);assert evidence['sha256']==sha(runimage)
proof=json.loads((REPO/'build/alarm-code/result.json').read_text());code=(REPO/'build/alarm-code/Code').read_bytes()
assert proof['status']=='PASS' and proof['sha256']==sha(code) and proof['source_sha256']==sha(pinned('bas/AlarmSrc,ffb'))
# (name, data, filetype, source, attributes): Alarms is writable (wr/r).
app=[('!Boot',pinned('Resources/!Boot,feb'),0xfeb,'src/Alarm/Resources/!Boot,feb',0x11),
 ('!Help',pinned('Resources/UK/!Help'),0xfff,'src/Alarm/Resources/UK/!Help',0x11),
 ('!Run',pinned('Resources/!Run,feb'),0xfeb,'src/Alarm/Resources/!Run,feb',0x11),
 ('!RunImage',runimage,0xffb,'src/Alarm/bas/!RunImage,ffb (squished)',0x11),
 ('Alarms',pinned('Resources/Alarms,ae9'),0xae9,'src/Alarm/Resources/Alarms,ae9',0x13),
 ('Code',code,0xffd,'build/alarm-code/Code (generated by src/Alarm/bas/AlarmSrc,ffb)',0x11),
 ('Messages',pinned('Resources/UK/Messages'),0xfff,'src/Alarm/Resources/UK/Messages',0x11),
 ('Templates',pinned('Resources/UK/Templates,fec'),0xfec,'src/Alarm/Resources/UK/Templates,fec',0x11)]
readme=(SRC/'ArcLibre/alarm/ReadMe').read_bytes()
stamp=int((datetime.datetime(2026,10,28)-datetime.datetime(1900,1,1)).total_seconds())*100
def typed(t):return 0xfff00000|(t<<8)|(stamp>>32),stamp&0xffffffff
# Old-map ADFS D: $ at &400, the !Alarm directory at &C00, files 1 KiB aligned.
disc=bytearray(819200);APPDIR=0xc00;offset=APPDIR+2048;rows=[];entries=[]
def place(name,data,ft,attributes):
 global offset
 disc[offset:offset+len(data)]=data;load,exe=typed(ft);e=entry(name,offset//256,data,load=load,execute=exe);e['attributes']=attributes
 offset+=(len(data)+1023)&~1023;return e
for name,data,ft,source,attributes in app:
 entries.append(place(name,data,ft,attributes));rows.append(dict(path='$.!Alarm.'+name,source=source,filetype='&%03X'%ft,bytes=len(data),sha256=sha(data),sector=entries[-1]['address']))
disc[APPDIR:APPDIR+2048]=directory('!Alarm',4,entries,b'Hugo')
top=[entry('!Alarm',APPDIR//256,directory=True),place('ReadMe',readme,0xfff,0x11)]
rows.append(dict(path='$.ReadMe',source='src/ArcLibre/alarm/ReadMe',filetype='&FFF',bytes=len(readme),sha256=sha(readme),sector=top[1]['address']))
disc[0x400:0xc00]=directory('$',4,top,b'Hugo')
u24(disc,0,offset//256);u24(disc,256,(819200-offset)//256);u24(disc,252,3200)
title=b'Alarm     '
for i in range(5):disc[247+i]=title[2*i];disc[502+i]=title[2*i+1]
disc[507:509]=b'\x41\x4c';disc[510]=3;disc[255]=oldcheck(disc[:255]);disc[511]=oldcheck(disc[256:511])
(ROOT/'arclibre-alarm.adf').write_bytes(disc)
(ROOT/'disc.json').write_text(json.dumps(dict(status='PASS',image='build/alarm-disc/arclibre-alarm.adf',sha256=sha(disc),bytes=len(disc),format='ADFS D (old map) 800K',disc_name='Alarm',
 files=rows,squish=dict(evidence,names=names),generated_code=proof),indent=2)+'\n')
print('floppy:',ROOT/'arclibre-alarm.adf',sha(disc),flush=True)
