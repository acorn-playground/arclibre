"""Build the pinned SharedCLibrary/FilerAct cohort; candidates only."""
import hashlib,json,os,pathlib,re,shutil,subprocess
from paths import REPO,SRC,HOST
from aof import read as read_aof
ROOT=REPO/'build/desktop-c-runtime';ROOT.mkdir(exist_ok=True)
for row in json.loads((REPO/'manifests/desktop-c-inputs.json').read_text()):
 b=(SRC/row['component']/row['path']).read_bytes();assert hashlib.sha256(b).hexdigest()==row['sha256'] and len(b)==row['bytes'],row
CC=REPO/'build/c-toolchain-release/install/bin/gcc';LD=CC.parent/'drlink'
inc=ROOT/'include';inc.mkdir(exist_ok=True);hdr=ROOT/'Hdr';hdr.mkdir(exist_ok=True)
headers=json.loads((REPO/'build/desktop-actions/headers.json').read_text())
for n,r in headers.items():
 p=hdr/n;p.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(SRC/r['source'].removeprefix('src/'),p)
shutil.copy2(SRC/'RISC_OSLib/hdr/SharedCLib',hdr/'SharedCLib');headers['SharedCLib']={}
env=dict(os.environ,HDR_PATH=str(hdr),MACHINE='A440')
def save(name,obj):(ROOT/name).write_text(json.dumps(obj,indent=2)+'\n')
def run(cmd,cwd,log):
 with (ROOT/log).open('w') as f:subprocess.run([str(v) for v in cmd],cwd=cwd,env=env,stdout=f,stderr=subprocess.STDOUT,check=True)
def asm(source,name,cwd,defines=(),generated=False):
 p=ROOT/(name+'.o');run([HOST/'bin/asasm',*([] if generated else ['-Uppercase']),'-cpu=ARM2','-apcs','3/26bit','-aof',*defines,source,p],cwd,name+'.log');return p
# Preserve original names and expose Unix include spellings. No header bodies
# are synthesized except swis.h, generated by the original source generator.
for parent in ['RISC_OSLib/clib/h','RISC_OSLib/rlib/h','RISC_OSLib/h']:
 for p in (SRC/parent).rglob('*'):
  if p.is_file():
   rel=str(p.relative_to(SRC/parent)).replace('/','.').lower()
   for name in ['h.'+rel,rel+'.h']:(inc/name).write_bytes(p.read_bytes())
s=(SRC/'RISC_OSLib/s/makehswis').read_text();omitted=[]
def profile(m):
 if m[1] in headers or m[1] in ['CPU.Generic26','IO.GenericIO']:return m[0]
 omitted.append(m[1]);return '; Not exported in this original-machine profile: '+m[0].strip()
s='        AREA CHeader, DATA, READONLY\n'+re.sub(r'^\s*GET\s+Hdr:(\S+)',profile,s,flags=re.M)
(ROOT/'makehswis.s').write_text(s);a=read_aof(asm(ROOT/'makehswis.s','swis',REPO));assert len(a['areas'])==1 and not a['areas'][0]['relocations'];b=a['areas'][0]['data'].rstrip(b'\0')
for n in ['swis.h','h.swis']:(inc/n).write_bytes(b)
save('header-profile.json',dict(omitted_unneeded_interfaces=omitted,sha256=hashlib.sha256(b).hexdigest()))
# GCC's vintage AOF writer creates a separate area at every section switch.
# AsAsm permits re-entry. Collect each object's code and writable statics,
# materialising zero bytes because the historic library copies a ROM template.
# COMMON areas declare their symbol via the area name; supply its real label.
from c_build_support import normalise,original_unchecked_prologues
unchecked=[]

flags=['-mcpu=arm2','-mapcs-26','-mlibscl','-mmodule','-Os','-fno-builtin','-fno-common','-nostdinc','-I'+str(inc)]
libflags=['-mlibrary-static-data-offset','-DDDE','-DSHARED_C_LIBRARY','-DUROM','-DFIELDNUM','-DBIG_WINDOWS','-DSETOPTIONS','-DALLOW_OLD_PATTERNS','-DSET_MISC_OPTIONS','-DLIB_SHARED="Shared "','-DLIB_APCS="R"','-DSEPERATE_MEMCPY']
save('build-options.json',dict(compiler=str(CC),flags=flags,library_flags=libflags))
def cbuild(source,name,library):
 raw=ROOT/(name+'.gcc.s');run([CC,*flags,*(libflags if library else ['-Dmain=ArcLibre_FilerActMain']),'-S','-x','c',source.relative_to(REPO),'-o',raw],REPO,name+'-cc.log')
 generated=raw.read_text()
 if library and name in ['lib-alloc','lib-flex']:
  original=source.read_text()
  if name=='lib-alloc':
   assert original.count('#pragma -s1')==1 and '#pragma -s0' not in original
   selected=None # original -s1 precedes every allocator function and lasts to EOF
  else:
   assert re.search(r'#pragma -s1\s+static int flex__budge.*?#pragma -s0',original,re.S)
   selected={'flex__budge'}
  generated,changed=original_unchecked_prologues(generated,selected)
  unchecked.append(dict(source=str(source.relative_to(REPO)),source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),functions=changed,reason='Preserve original Norcroft -s1 stack allocator/extension contract'))
 gen=ROOT/(name+'.s');gen.write_text(normalise(generated));return asm(gen,name,REPO,generated=True)
make=(SRC/'RISC_OSLib/Makefile').read_text();groups={};objects={};private={}
for group in ['RM_OBJS','ROM_OBJS']:
 text=re.search(r'^'+group+r' =(.*?)(?=\n[^ #\\\n])',make,re.M|re.S).group(1)
 names=re.findall(r'rm_o(?:_rl)?\.(\w+)',text);groups[group]=names;private[group]=0
 for name in names:
  c=next((p for p in (SRC/'RISC_OSLib').glob('**/c/'+('bsearch' if name=='bsearch_a' else name))),None)
  if c:
   objects[name]=cbuild(c,'lib-'+name,True);private[group]+=sum(a['size'] for a in read_aof(objects[name])['areas'] if not a['attributes']&0x2000)
save('unchecked-stack-prologues.json',unchecked)
save('private-data.json',private);assert private['RM_OBJS']<=490*4 and private['ROM_OBJS']<=607*4
special=dict(k_modbody='kernel/s/k_mod_r',cl_modbody='clib/s/cl_mod_r',rl_modbody='rlib/s/rl_mod_r',initmodule='rlib/s/initmod_r')
for name in sorted(set(groups['ROM_OBJS']+groups['RM_OBJS']),key=lambda n:(n in ['cl_spare','rl_spare'],n)):
 if name in objects:continue
 source=SRC/'RISC_OSLib'/special[name] if name in special else next((SRC/'RISC_OSLib').glob('**/s/'+name))
 defines=[]
 if name in ['cl_spare','rl_spare']:
  n='CLib' if name=='cl_spare' else 'RLib';v=private['RM_OBJS' if n=='CLib' else 'ROM_OBJS'];defines=['-PreDefine=ArcLibre_'+n+'PrivateBytes SETA '+str(v)]
 objects[name]=asm(source,'asm-'+name,SRC/'RISC_OSLib',defines)
 if name not in ['k_modbody','cl_modbody','rl_modbody','cl_spare','rl_spare']:
  group='RM_OBJS' if name in groups['RM_OBJS'] else 'ROM_OBJS'
  private[group]+=sum(a['size'] for a in read_aof(objects[name])['areas'] if not a['attributes']&0x2000)
save('private-data.json',private)
objects['gcc-div']=asm(SRC/'ArcLibre/s/GCCDiv','gcc-div',REPO)
# Drlink inserts equal-named areas in reverse object order. Reverse the original
# Makefile order so public kernel/C/RLib data prefixes retain their contracts.
order=['cl_rmhdr','initmodule']+groups['RM_OBJS']+groups['ROM_OBJS'][2:]+['gcc-div']
assert len(order)==len(set(order)),order
base=int(os.environ.get('ARCLIBRE_CLIB_BASE','0x03950000'),0)
run([LD,'-bin','-base',hex(base),'-map','-symbols',ROOT/'SharedCLib.symbols','-output',ROOT/'SharedCLib.bin',*[objects[n] for n in reversed(order)]],REPO,'link.log')
save('link-inputs.json',dict(base=base,objects={n:str(p.relative_to(REPO)) for n,p in objects.items()},order=order,private_data=private))
print('SharedCLibrary candidate linked:',(ROOT/'SharedCLib.bin').stat().st_size,'bytes; not yet runtime validated',flush=True)
# FilerAct uses the matching original C application/module wrapper and ROM
# entry veneers. Its statics remain separate from the fixed shared-library ABI.
filer={}
for p in (SRC/'FilerAct/h').iterdir():
 if p.is_file():shutil.copy2(p,inc/(p.name+'.h'))
# The link order is fixed here, not taken from the directory listing, whose
# order differs between filesystems. This is the order the released ROMs link
# (the macOS APFS listing they were first built from).
sources=['actionwind','Buttons','memmanage','Initialise','Chains','listfiles','debug']
assert sorted(sources)==sorted(p.name for p in (SRC/'FilerAct/c').iterdir() if p.is_file()),'place a new FilerAct source in the link order'
for name in sources:filer[name]=cbuild(SRC/'FilerAct/c'/name,'filer-'+name,False)
work=ROOT/'FilerAct';shutil.copytree(SRC/'FilerAct',work,dirs_exist_ok=True);shutil.copy2(SRC/'RISC_OSLib/s/modulewrap',work/'s/ModuleWrap')
for n in ['ModuleWrap','allerrs']:filer[n]=asm('s/'+n,'filer-'+n,work)
filer['romstubs']=asm('rlib/s/rl_stub_rm','filer-romstubs',SRC/'RISC_OSLib')
filer['c-entry']=asm(SRC/'ArcLibre/s/FilerCEntry','filer-c-entry',REPO)
save('filer-inputs.json',dict(objects={n:str(p.relative_to(REPO)) for n,p in filer.items()}))
import struct
resources=bytearray();records=[]
for name,path,filetype in [('CLib.Messages','RISC_OSLib/clib/Resources/UK/Messages',0xfff),('RISC_OSLib.Messages','RISC_OSLib/rlib/Resources/UK/Messages',0xfff),('FilerAct.Messages','FilerAct/Resources/UK/Messages',0xfff),('FilerAct.Templates','FilerAct/Resources/UK/Templates,fec',0xfec)]:
 data=(SRC/path).read_bytes();n=('Resources.'+name).encode()+b'\0';n+=bytes(-len(n)%4);length=24+len(n)+((len(data)+3)&~3)
 resources+=struct.pack('<5I',length,0xfff00000|(filetype<<8),0,len(data),3)+n+struct.pack('<I',len(data)+4)+data+bytes(-len(data)%4)
 records.append(dict(name=name,source='src/'+path,sha256=hashlib.sha256(data).hexdigest(),filetype=filetype))
(ROOT/'resources.bin').write_bytes(resources+bytes(4));save('resources.json',records)
